function budget = estimate_mcu_budget()
% ESTIMATE_MCU_BUDGET Operation/RAM budgets, not a measured MCU benchmark.
% Reads resource counts from the build whose SOF hash matches the live project.
A=fileparts(mfilename('fullpath'));O=fullfile(A,'results');
if ~isfolder(O),mkdir(O);end
r=jsondecode(fileread(fullfile(A,'fpga_resources.json')));
fsRaw=165e6/144; decimation=32; fsIF=fsRaw/decimation;
rxSeconds=.019; frameSamples=floor(fsRaw*rxSeconds);
valid=672; nfft=1024; complexN=nfft/2;
cpuHz=170e6; ramBytes=32768;
combOutputs=floor(frameSamples/decimation);
butterflies=(complexN/2)*log2(complexN);
postPairs=nfft/4-1;
fftMult=4*butterflies+4*postPairs;
fftAdd=6*butterflies+10*postPairs+2;
eligibleBins=floor(2000/(fsIF/nfft))-ceil(25/(fsIF/nfft))+1;
neighborPowerBins=eligibleBins+2;
task=["Digital RX x reference mixing (new)";"CIC3 integrators"; ...
    "CIC3 combs";"Frame sum and DC removal";"Kaiser4 window"; ...
    "1024 real FFT: 512 complex FFT + split";"Power at all 513 bins"; ...
    "Peak comparison in bins 1 to 57";"Peak interpolation"];
mult=[frameSamples;0;0;0;valid;fftMult;2*(nfft/2+1);0;0];
add=[0;3*frameSamples;3*combOutputs;2*valid;0;fftAdd;nfft/2+1;0;0];
other=["Rescaling/saturation/memory access excluded";"40-bit FPGA states: typically 64-bit MCU arithmetic"; ...
    "One decimated output per 32 raw samples";"One mean division per frame"; ...
    "Precomputed coefficients, no runtime Bessel evaluation"; ...
    "Expression counts, not optimized CMSIS instructions"; ...
    "Only 59 bins are needed for equivalent peak/neighbour processing"; ...
    "57 eligible bins, approximately 56 max comparisons"; ...
    "3 logarithms and 1 divide, or existing 48-squaring fixed algorithm"];
operations=table(task,mult,add,other,'VariableNames',{'Stage','RealMultiplications','AddSubtracts','Notes'});
writetable(operations,fullfile(O,'operations_per_frame.csv'));

cyclesPerPair=[32;64;96;128;160];
streamUtil=100*cyclesPerPair*fsRaw/cpuHz;
streamCPUms=cyclesPerPair*frameSamples/cpuHz*1000;
cpuScenarios=table(cyclesPerPair,streamUtil,streamCPUms,cyclesPerPair<cpuHz/fsRaw, ...
    'VariableNames',{'AssumedCyclesPerSample','CaptureCPU_percent','CPUWorkPer19msFrame_ms','BelowHardDeadline'});
writetable(cpuScenarios,fullfile(O,'cpu_scenarios.csv'));
% DMA sizing: two halves of 512 sample pairs, two 16-bit channels per pair.
dmaHalfPairs=512;
dmaHalfPeriodUs=dmaHalfPairs/fsRaw*1e6;
dmaHalfCycles=dmaHalfPairs/fsRaw*cpuHz;
names=["RFFT input/work buffer";"RFFT output buffer";"Dual ADC DMA, 2 halves x 512 pairs"; ...
    "Filter state, telemetry and scratch reserve";"Application/HAL/stack reserve"; ...
    "Optional runtime PWM ARR/CCR table";"Optional current RX waveform buffer"; ...
    "Optional sine-reference DAC ping-pong buffer"];
bytes=[nfft*4;nfft*4;2*dmaHalfPairs*2*2;1024;4096;800*2*2;r.raw_display_points*2;2*512*2];
memory=table(names,bytes,bytes/1024,'VariableNames',{'Allocation','Bytes','KiB'});
writetable(memory,fullfile(O,'memory_budget.csv'));
baseRAM=sum(bytes(1:5));withPWM=baseRAM+bytes(6);withWave=withPWM+bytes(7);
withAnalogReference=withWave+bytes(8);

entity=struct2table(r.entities);
writetable(entity,fullfile(O,'fpga_entities.csv'));
fftNode=r.entities(strcmp({r.entities.entity},'MainFftProcessor'));
fifoNode=r.entities(strcmp({r.entities.entity},'MainWaveFifo'));
fifoPercent=100*fifoNode.memory_bits/r.totals.memory_bits;
% Published comparison is a COMPLEX Q15/Q31 FFT on another M4, not G431 RFFT.
published=struct('device','STM32F429','clock_hz',180e6,'points',1024, ...
    'transform','Complex FFT, radix 4','q15_cycles',82299,'q31_cycles',153307, ...
    'q15_same_cycle_estimate_at_170MHz_ms',82299/cpuHz*1000, ...
    'q31_same_cycle_estimate_at_170MHz_ms',153307/cpuHz*1000, ...
    'measured_on_G431',false);
budget=struct('date','2026-10-22','target_mcu','STM32G431RBT6','cpu_hz',cpuHz,'sram_bytes',ramBytes, ...
    'raw_fs_hz',fsRaw,'fft_fs_hz',fsIF,'rx_window_ms',19,'raw_samples_per_frame',frameSamples, ...
    'effective_samples',valid,'fft_length',nfft,'search_bins',eligibleBins, ...
    'raw_one_channel_frame_bytes',2*frameSamples,'raw_two_channel_frame_bytes',4*frameSamples, ...
    'hard_cycles_per_sample_pair',cpuHz/fsRaw,'half_budget_cycles_per_sample_pair',cpuHz/fsRaw/2, ...
    'dma_half_pairs',dmaHalfPairs,'dma_half_deadline_us',dmaHalfPeriodUs,'dma_half_cycle_budget',dmaHalfCycles, ...
    'real_fft_complex_butterflies',butterflies,'fft_real_mult_expressions',fftMult,'fft_add_expressions',fftAdd, ...
    'cic_add_sub_per_frame',3*frameSamples+3*combOutputs, ...
    'all_bin_power_multiplies',2*(nfft/2+1),'restricted_power_bins',neighborPowerBins, ...
    'restricted_power_multiplies',2*neighborPowerBins, ...
    'planned_peak_only_ram_bytes',baseRAM,'planned_peak_plus_pwm_ram_bytes',withPWM, ...
    'planned_peak_pwm_wave_ram_bytes',withWave,'planned_with_analog_reference_buffer_bytes',withAnalogReference, ...
    'window_twiddle_and_phase_lut_storage','Const in Flash; exact tables/linker map must be checked', ...
    'raw_wave_buffer_fraction_of_fpga_configured_memory_percent',fifoPercent, ...
    'latest_fpga_fft_branch',fftNode,'latest_fpga_totals',r.totals, ...
    'published_fft_reference',published,'mcu_cycles_measured',false, ...
    'fft_planning_allowance_ms',[0.5 1.5], ...
    'fft_planning_allowance_is_measurement',false, ...
    'full_wave_uart_ms',r.full_stream_bytes*10/2e6*1000, ...
    'peak_only_uart_ms',r.peak_packet_bytes*10/2e6*1000, ...
    'fpga_fft_latency_ms',23430/50e6*1000, ...
    'fpga_interpolation_latency_us',140/50e6*1e6, ...
    'fpga_range_latency_us',168/50e6*1e6);
writeText(fullfile(O,'checks.json'),jsonencode(budget,PrettyPrint=true));
save(fullfile(O,'budget_data.mat'),'budget','operations','cpuScenarios','memory','entity');
writeReport(O,r,budget,operations,cpuScenarios,memory);
disp(operations);disp(cpuScenarios);disp(memory);
disp("Hard capture budget: "+budget.hard_cycles_per_sample_pair+" cycles per sample pair.");
disp("Planning RAM with PWM and retained waveform: "+withWave/1024+" KiB.");
disp("This is a budget estimate. No MCU firmware benchmark was performed.");
end

function writeText(filename,txt)
f=fopen(filename,'w','n','UTF-8');assert(f>=0);cleanup=onCleanup(@() fclose(f));
fprintf(f,'%s',txt);
end

function writeReport(O,r,b,ops,cpu,mem)
entityRows="";
selected={'MainTxController','MainRxController','MainFftProcessor','kaiser4_rfft', ...
    'fft_power_peak','main_peak_interpolator','MainRangeCalculator','MainWaveFifo'};
for k=1:numel(selected)
 v=r.entities(strcmp({r.entities.entity},selected{k}));
 entityRows=entityRows+sprintf('<tr><td>%s</td><td>%.1f</td><td>%d</td><td>%.3f</td><td>%d</td></tr>',v.entity,v.alms,v.dsp,v.memory_bits/8192,v.m10k);
end
operationRows="";
for k=1:height(ops)
 operationRows=operationRows+sprintf('<tr><td>%s</td><td>%d</td><td>%d</td><td>%s</td></tr>',ops.Stage(k),ops.RealMultiplications(k),ops.AddSubtracts(k),ops.Notes(k));
end
cpuRows="";
for k=1:height(cpu)
 cpuRows=cpuRows+sprintf('<tr><td>%d</td><td>%.1f%%</td><td>%.3f ms</td></tr>',cpu.AssumedCyclesPerSample(k),cpu.CaptureCPU_percent(k),cpu.CPUWorkPer19msFrame_ms(k));
end
memRows="";
for k=1:height(mem)
 memRows=memRows+sprintf('<tr><td>%s</td><td>%d</td><td>%.3f</td></tr>',mem.Allocation(k),mem.Bytes(k),mem.KiB(k));
end
