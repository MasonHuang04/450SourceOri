"""Chirp entry: shared settings -> board constants -> Questa -> waveform plots."""
from pathlib import Path
import argparse,json,struct,math,shutil,subprocess,hashlib,sys
import numpy as np
HERE=Path(__file__).resolve().parent;V=HERE.parents[1];RTL=V/'SourceCode'
p=argparse.ArgumentParser();p.add_argument('--prepare',action='store_true');p.add_argument('--analyze',action='store_true');p.add_argument('--settings-only',action='store_true')
p.add_argument('--vsim',default='E:/Downloads/Questa/questa_fse/win64/vsim.exe');a=p.parse_args()
OUT=HERE/'results/run';OUT.mkdir(parents=True,exist_ok=True)
sys.path.insert(0,str(HERE.parent))
from source_units import SourceTree
tree=SourceTree(RTL,OUT)
cfg=json.loads((HERE/'settings.json').read_text());hz=165000000
assert 0<cfg['start_hz']<=cfg['end_hz']<hz/2
assert 0<cfg['duration_ms']<cfg['repeat_ms'] and cfg['boot_ms']>1 and 0<cfg['amplitude']<=1
stride=int(cfg['plot_sample_stride']);assert stride>0 and hz/stride>2*cfg['end_hz']
fp=lambda x:struct.pack('>f',float(x)).hex()
fc=np.float32((cfg['start_hz']+cfg['end_hz'])/2);bw=np.float32(cfg['end_hz']-cfg['start_hz']);tc=np.float32(cfg['duration_ms']/1000)
f0=np.float32(fc-np.float32(bw*np.float32(.5)));slope=np.float32(bw/tc)
ticks=int(np.rint(np.float32(tc*np.float32(hz))));samples=math.ceil(ticks/stride)
def prepare():
 constants={'FC':fp(fc),'BW':fp(bw),'TC':fp(tc),'AMPLITUDE':fp(cfg['amplitude']),'F0':fp(f0),'SLOPE':fp(slope)}
 text='-- Generated by Simulation/Chirp/run.py from settings.json.\nlibrary ieee;use ieee.std_logic_1164.all;\npackage ChirpSettings is\n'
 text+=''.join(f' constant CFG_{k}:std_logic_vector(31 downto 0):=x"{v}";\n' for k,v in constants.items())
 for k,v in dict(BOOT_CYCLES=round(cfg['boot_ms']*hz/1000),PERIOD_CYCLES=round(cfg['repeat_ms']*hz/1000),TX_CYCLES=ticks,PLOT_SAMPLES=samples,PLOT_STRIDE=stride).items():text+=f' constant CFG_{k}:positive:={v};\n'
 text+='end package;\n';(RTL/'ChirpSettings.vhd').write_text(text)
 if a.settings_only:return
 files=[];cmd=['vlib work','vmap work work','vlib real_ip','vmap real_ip real_ip']
 def add(lib,f):files.append(f);cmd.append('vcom -2008 -work '+lib+' {'+f.as_posix()+'}')
 for n in ['SysLib.vhd','DSP/FPFAdd/FPFAdd/dspba_library_package.vhd','DSP/FPFAdd/FPFAdd/dspba_library.vhd']:add('real_ip',tree.file(n))
 for n in ['FPFAdd','FPFSub','FPFMult','FPFDiv','FPFCos','FPFFP32ToInt32','FPFInt32ToFP32']:
  add('real_ip',RTL/'DSP'/n/n/(n+'_0002.vhd'));add('real_ip',RTL/'DSP'/n/(n+'.vhd'))
 for n in ['DSPLib.vhd','DSP/FIFO.vhd','ChirpWaveGen.vhd']:add('real_ip',tree.file(n))
 for f in [RTL/'ChirpSettings.vhd',tree.file('ScopeBurstControl.vhd'),HERE/'tb_chirp_plot.vhd',HERE/'tb_chirp_board_control.vhd']:add('work',f)
 for f in (RTL/'DSP').rglob('*.hex'):shutil.copy2(f,OUT/f.name)
 for top in ['tb_chirp_board_control','tb_chirp_plot']:
  cmd+=['vsim -onfinish stop -t 1fs -L altera_mf -L altera_lnsim -L lpm -L real_ip work.'+top,'run -all','quit -sim']
 (OUT/'compile_and_run.do').write_text('\n'.join(cmd)+'\n')
 (OUT/'source_sha256.json').write_text(json.dumps({str(f):hashlib.sha256(f.read_bytes()).hexdigest() for f in tree.ledger(files)},indent=2))
 (OUT/'settings_used.json').write_text(json.dumps(cfg,indent=2))
def analyze():
 import matplotlib
 matplotlib.use('Agg');import matplotlib.pyplot as plt
 assert json.loads((OUT/'settings_used.json').read_text())==cfg,'Settings changed since simulation; rerun first.'
 ledger=json.loads((OUT/'source_sha256.json').read_text());assert all(hashlib.sha256(Path(f).read_bytes()).hexdigest()==h for f,h in ledger.items())
 data=np.loadtxt(OUT/'chirp_stream.csv',delimiter=',',dtype=np.int64)
 idx=np.r_[np.arange(samples)*stride,ticks-1];t=idx/hz;got=data[105:105+len(idx),2]
 ideal=np.rint(8192+8191*cfg['amplitude']*np.cos(2*np.pi*(float(f0)*t+.5*float(slope)*t*t)))
 err=np.abs(got-ideal);assert max(err)<=cfg['max_dac_error_codes']
 np.savetxt(HERE/'results/chirp_samples.csv',np.column_stack([idx,t,got,ideal,got-ideal]),delimiter=',',header='system_index,time_s,dac_code,ideal_code,error_code',comments='',fmt=['%d','%.12f','%d','%d','%d'])
 fig,ax=plt.subplots(2,1,figsize=(9,6),layout='constrained')
 show=t<.0002;ax[0].plot(t[show]*1e6,got[show],label='RTL DAC codes');ax[0].set(xlabel='Waveform time (us)',ylabel='DAC code',title='Chirp start: real Intel IP');ax[0].grid(alpha=.2)
 nfft=min(4096,2**int(np.floor(np.log2(max(64,samples//4)))))
 ax[1].specgram(got[:samples]-8192,NFFT=nfft,Fs=hz/stride,noverlap=nfft*3//4,cmap='viridis')
 ax[1].set(xlabel='Waveform time (s)',ylabel='Frequency (Hz)',ylim=(max(0,cfg['start_hz']-5000),cfg['end_hz']+5000),title='Chirp spectrogram (sample-index checkpoints)')
 fig.savefig(HERE/'results/chirp.png',dpi=150);plt.close(fig)
 result=dict(pass_all=True,points=len(idx),maximum_dac_error_codes=int(max(err)),settings=cfg,scope='Real Intel Chirp core at sampled indices, plus accelerated auto-trigger controller test. Not continuous full-top or analog simulation.')
 (HERE/'results/checks.json').write_text(json.dumps(result,indent=2));print(json.dumps(result,indent=2))
if a.prepare or a.settings_only:prepare()
elif a.analyze:analyze()
else:
 prepare();script=OUT/'batch.do';script.write_text('onerror {quit -code 1 -force}\nonbreak {quit -code 1 -force}\ndo compile_and_run.do\nquit -code 0 -force\n')
 with (OUT/'simulation.log').open('w') as log:code=subprocess.run([a.vsim,'-c','-do',str(script)],cwd=OUT,stdout=log,stderr=subprocess.STDOUT,timeout=300).returncode
 text=(OUT/'simulation.log').read_text();assert code==0 and 'PASS SCOPE BURST CONTROL' in text and 'PASS QUARTER AMPLITUDE EXPORT' in text,text[-4000:]
 analyze()
